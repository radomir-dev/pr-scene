import { writeFile } from "node:fs/promises";
import octicons from "@primer/octicons";

const NAMES = [
  "git-pull-request",
  "git-pull-request-closed",
  "git-merge",
  "comment",
  "kebab-horizontal",
  "chevron-down",
  "check-circle-fill",
  "x-circle-fill",
  "dot-fill",
  "info",
  "light-bulb",
  "report",
  "alert",
  "stop",
];

const entries = NAMES.map((name) => {
  const path = octicons[name]?.heights?.["16"]?.path;
  if (!path) throw new Error(`no 16px path for ${name}`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(path)},`;
});

const source = `// Generated by scripts/generate-icons.mjs from @primer/octicons. Do not edit.

export const ICON_PATHS = {
${entries.join("\n")}
} as const;
`;

await writeFile(new URL("../src/icon-data.ts", import.meta.url), source);
console.log(`wrote ${NAMES.length} icon paths to src/icon-data.ts`);
